  dam_id UUID REFERENCES public.animals(id) ON DELETE SET NULL,
  cage_number TEXT,
  origin TEXT,
  entry_date DATE,
  first_breeding_date DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at TIMESTAMPTZ
);

